// Generates .claude/conventions/_router.md: the map a session reads first. It holds no knowledge,
// only where knowledge lives and when to read it, so it stays small however much the kit grows.
// It is also where kit-core-dotnet learns the stack: its official layer, tools and failure classes.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { readFrontmatter, readText } from './util.mjs';
import { routerFacts } from './scanners.mjs';

export const PLUGIN_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');

const TOPIC_TRIGGERS = {
  workspace: 'anything: SDK, target frameworks, projects, packages, build/test/run commands',
  architecture: 'adding or moving files or projects, namespaces, project references',
  data: 'entities, DbContext, queries, migrations, repositories, SaveChanges, schema',
  api: 'endpoints, controllers, OpenAPI, JSON, auth, outgoing HTTP',
  di: 'registering or resolving services, lifetimes, options, the composition root',
  ui: 'views, view models, XAML/Razor, commands, navigation, user-visible text',
  validation: 'input validation, error messages',
  mapping: 'DTOs, view-model lists, projections, mapping between layers',
  style: 'writing any C# (namespaces, fields, regions, comments, naming)',
  testing: 'tests, test projects, test data',
  lint: 'formatting, .editorconfig, analyzers',
  examples: 'creating a new file of a kind that already exists',
};

/** Contracts shipped with this plugin (the core ones are synced copies). */
export function listContracts() {
  const dirs = [path.join(PLUGIN_ROOT, 'contracts', 'core'), path.join(PLUGIN_ROOT, 'contracts')];
  const contracts = [];
  for (const dir of dirs) {
    if (!fs.existsSync(dir)) continue;
    for (const file of fs.readdirSync(dir).sort()) {
      if (!file.endsWith('.md') || file === 'README.md') continue;
      const text = readText(path.join(dir, file));
      const meta = readFrontmatter(text) ?? {};
      contracts.push({ file: path.join(dir, file), text, ...meta, name: meta.name ?? file.replace(/\.md$/, '') });
    }
  }
  return contracts;
}

export function buildRouter(ctx, topics, hasDecisions) {
  const f = routerFacts(ctx);
  const applies = (c) => !c.requires || (c.requires === 'efcore' && f.efCore) || (c.requires === 'aspnetcore' && f.aspnetcore);
  const contracts = listContracts().filter(applies);
  const pad = (s, n) => s.padEnd(n);
  const failureRows = [
    ['`DbUpdateConcurrencyException`, an edit silently overwritten, wrong counter or stock', '`lost-update`'],
    ['`NullReferenceException` far from the change, insert fails on NOT NULL, blank field', '`nullability-across-layers`'],
    f.efCore && ['pending model changes, migration fails elsewhere, missing column', f.codeFirst ? '`migration-history`, `/ef-migration`' : '`migration-history`, `/db-scaffold`'],
    ['orphan rows, half-done delete, duplicate e-mail or message after a retry', '`commit-side-effect-order`'],
    ['a date off by an hour or a day, wrong date order', '`time-kind`'],
    f.aspnetcore && ['client gets null where the spec says required, enum as number', '`api-spec-fidelity`, `/openapi-export`'],
    ['"Cannot consume scoped service from singleton", "A second operation was started on this context", data of another user', '`lifetime-matched-injection`'],
    f.efCore && ['slow page, N+1, too many queries, cartesian explosion', 'the `optimizing-ef-core-queries` skill'],
    ['SDK, dotnet-ef, LSP or MCP not starting, project can\'t be built here', '`dotnet-tooling`, `setup` skill'],
    ['after a .NET upgrade, obsolete API warnings', '`/dotnet-upgrade`'],
  ].filter(Boolean);
  const lines = [
    '# Kit router',
    '',
    '<!-- generated by `kit-dotnet scan` · do not edit · imported from CLAUDE.md -->',
    '',
    'Look things up; don\'t answer from memory. Read the file a task touches before changing that area.',
    '',
    '## Conventions: what this repo does (generated facts)',
    '',
    `| ${pad('File', 42)} | Read when the task touches |`,
    `| ${'-'.repeat(42)} | ------------------------- |`,
    ...topics.map((t) => `| ${pad('.claude/conventions/' + t + '.md', 42)} | ${TOPIC_TRIGGERS[t] ?? t} |`),
    `| ${pad('.claude/.state/inventory.md', 42)} | finding a symbol: grep it, never read it whole |`,
    '',
    '## Decisions: what the team chose (hand-written, wins over generated facts)',
    '',
    hasDecisions
      ? '- `.claude/decisions/conventions.md`: confirmed rules with their exceptions\n- `.claude/decisions/traps.md`: non-obvious decisions that look like bugs; skim before any change\n- `.claude/decisions/adr/`: architecture decisions'
      : '- none yet: run the `convention-creator` skill after a scan',
    '',
    '## Contracts: how to reason about a failure class',
    '',
    'Read one with `kit-dotnet contract <name>` when its trigger applies.',
    '',
    `| ${pad('Contract', 30)} | Applies when |`,
    `| ${'-'.repeat(30)} | ------------ |`,
    ...contracts.map((c) => `| ${pad(c.name, 30)} | ${c['applies-when'] ?? ''} |`),
    '',
    '## Failure classes (used by the error-classifier skill)',
    '',
    '| Signal | Route to |',
    '| ------ | -------- |',
    ...failureRows.map(([signal, route]) => `| ${signal} | ${route} |`),
    '',
    '## Priority on conflict (say the conflict out loud, never pick silently)',
    '',
    '1. contract  2. decisions  3. conventions  4. official .NET skills + Microsoft Learn  5. your own knowledge',
    '',
    '## Tools: the official layer',
    '',
    '- C# and .NET questions → the `csharp-expert` skill (dotnet plugin); refactoring → the `csharp-refactoring` skill',
    f.efCore ? '- EF Core queries, tracking, loading → the `optimizing-ef-core-queries` skill' : null,
    f.aspnetcore ? '- Endpoints, HTTP semantics, OpenAPI → the `dotnet-webapi` skill' : null,
    '- Version-dependent or API-reference questions → Microsoft Learn MCP (`microsoft-learn`): search, then fetch the page',
    '- Package versions, compatibility, vulnerabilities → NuGet MCP (`nuget`)',
    '- Major upgrades → `/dotnet-upgrade`, which uses the dotnet-upgrade migration skills',
    '- Symbol, references → LSP (Roslyn); if it does not answer → grep `.claude/.state/inventory.md`',
    '- Build and tests → the commands in workspace.md',
    f.efCore && f.codeFirst ? '- After a model change → `dotnet ef migrations has-pending-model-changes` (see data.md for the project pair)' : null,
    f.windowsOnly.length ? `- ${f.windowsOnly.join(', ')}: Windows-only; off Windows, build the other projects and say what was not built` : null,
    '- A tool not available: say so once, use the fallback, keep working.',
    '',
    '## Freshness',
    '',
    '- `kit-dotnet stale` lists conventions that no longer match the code. Stale ⇒ say so, then run `kit-dotnet scan`.',
    '',
    '## The loop',
    '',
    'Look up the rules → ask the official layer for framework questions → build → LSP + build/test →',
    'run the `codecraft` skill on the diff → report what was applied, skipped, and not checkable.',
    '',
  ].filter((l) => l !== null);
  return lines.join('\n');
}
