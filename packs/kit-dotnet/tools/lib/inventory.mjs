// Symbol index and internal-package scans. The inventory is gitignored: it changes with almost
// every commit, and the Roslyn language server answers the same questions live.
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { readText } from './util.mjs';
import { typeDeclarations } from './scanners.mjs';

function lineOf(text, index) {
  return text.slice(0, index).split('\n').length;
}

export function buildInventory(ctx) {
  const rows = [];
  const prefix = ctx.ws === '.' ? '' : ctx.ws + '/';
  const row = (kind, name, project, file, line) => rows.push(`${kind.padEnd(11)} ${name.padEnd(40)} ${project.padEnd(28)} ${prefix}${file}:${line}`);
  for (const file of ctx.csFiles) {
    if (ctx.migrationFiles.includes(file)) continue;
    const text = ctx.read(file);
    const project = ctx.projectOf(file)?.name ?? '';
    for (const d of typeDeclarations(text)) {
      row(d.kind, d.name, project, file, lineOf(text, d.index));
    }
    for (const m of text.matchAll(/DbSet<\s*(\w+)\s*>\s+(\w+)/g)) {
      row('dbset', `${m[2]} (${m[1]})`, project, file, lineOf(text, m.index));
    }
    for (const m of text.matchAll(/\.Map(Get|Post|Put|Delete|Patch|Group)\s*\(\s*"([^"]*)"/g)) {
      row('endpoint', `${m[1].toUpperCase()} ${m[2]}`, project, file, lineOf(text, m.index));
    }
    for (const m of text.matchAll(/\[(Http(Get|Post|Put|Delete|Patch)|Route)\s*(?:\(\s*"([^"]*)"\s*\))?\]/g)) {
      row('route', `${m[2]?.toUpperCase() ?? 'ROUTE'} ${m[3] ?? ''}`.trim(), project, file, lineOf(text, m.index));
    }
  }
  return [
    '# Inventory',
    '',
    '<!-- generated by `kit-dotnet scan` · gitignored · grep it, never load it whole -->',
    '',
    `${'kind'.padEnd(11)} ${'name'.padEnd(40)} ${'project'.padEnd(28)} file:line`,
    ...rows.sort(),
    '',
  ].join('\n');
}

function nugetRoot() {
  return process.env.NUGET_PACKAGES || path.join(os.homedir(), '.nuget', 'packages');
}

/** Public types from the package's XML documentation file in the local NuGet cache. */
function publicApi(id, version) {
  if (!version) return [];
  const dir = path.join(nugetRoot(), id.toLowerCase(), version.toLowerCase(), 'lib');
  if (!fs.existsSync(dir)) return [];
  const names = new Set();
  for (const tfm of fs.readdirSync(dir).sort()) {
    const xml = readText(path.join(dir, tfm, `${id}.xml`));
    if (!xml) continue;
    for (const m of xml.matchAll(/<member\s+name="T:([^"`]+)/g)) names.add(m[1]);
    break;
  }
  return [...names].sort();
}

/** Internal NuGet packages (or projects) listed in .claude/kit.json → `packages`. */
export function scanPackages(ctx) {
  const results = [];
  for (const id of [...(ctx.kitConfig.packages ?? [])].sort()) {
    const project = ctx.projects.find((p) => p.name === id);
    const pinned = ctx.deps[id]?.join(' / ') ?? (project ? 'project reference' : 'not referenced');
    const resolved = project ? 'working tree' : ctx.resolved(id) ?? 'not referenced';
    const used = new Set();
    for (const file of ctx.codeFiles) {
      if (project && ctx.projectOf(file) === project) continue;
      for (const m of ctx.read(file).matchAll(/^\s*(?:global\s+)?using\s+(?:static\s+)?([\w.]+)\s*;/gm)) {
        if (m[1] === id || m[1].startsWith(id + '.')) used.add(m[1]);
      }
    }
    const exported = project
      ? ctx.codeFiles.filter((f) => ctx.projectOf(f) === project)
        .flatMap((f) => [...ctx.read(f).matchAll(/^\s*public\s+(?:(?:static|sealed|abstract|partial|readonly)\s+)*(class|interface|record|struct|enum)\s+(\w+)/gm)].map((m) => `${m[2]} (${m[1]})`))
        .sort()
      : publicApi(id, ctx.resolved(id));
    const lines = [
      `# Package ${id}`,
      '',
      '<!-- generated by `kit-dotnet scan` · do not edit · stale when `scanned` differs from `resolved` -->',
      '',
      `pinned:   ${pinned}`,
      `resolved: ${resolved}`,
      `scanned:  ${resolved}`,
      `source:   ${project ? 'project-reference' : 'nuget'}`,
      '',
      '## Used in this repo (namespaces)',
      '',
      ...(used.size ? [...used].sort().map((s) => `- ${s}`) : ['- nothing imported yet']),
      '',
      '## Public API (types)',
      '',
      ...(exported.length ? [...new Set(exported)].map((s) => `- ${s}`) : ['- documentation file not found in the NuGet cache; run dotnet restore and rescan']),
      '',
    ];
    results.push({ file: `packages/${id}.md`, content: lines.join('\n') });
  }
  return results;
}
