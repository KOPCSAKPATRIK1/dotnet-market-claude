// Project-side kit CLI. Runs inside a .NET repository (the git root holds .claude/).
//   kit init | scan [topic…] [--check] | stale | status | contract [name] | evidence [topic]
//   kit codecraft-done | hook-stop
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { loadContext } from './lib/context.mjs';
import { buildInventory, scanPackages } from './lib/inventory.mjs';
import { buildRouter, listContracts } from './lib/router.mjs';
import { routerFacts, SCANNERS } from './lib/scanners.mjs';
import { git, onPath, projectRoot, readJsonc, readText, sha256, writeIfChanged } from './lib/util.mjs';

/** Official plugins kit-dotnet depends on, from the .NET team's marketplace. */
const OFFICIAL_PLUGINS = ['dotnet', 'dotnet-data', 'dotnet-aspnetcore', 'dotnet-upgrade'];
const OFFICIAL_MARKETPLACE = 'dotnet-agent-skills';

const args = process.argv.slice(2);
const command = args[0] ?? 'help';
const flags = new Set(args.filter((a) => a.startsWith('--')));
const rootFlag = args.indexOf('--root');
const root = projectRoot(rootFlag >= 0 ? args[rootFlag + 1] : process.cwd());
const positional = args.slice(1).filter((a, i, all) => !a.startsWith('--') && all[i - 1] !== '--root');

const CLAUDE_DIR = path.join(root, '.claude');
const CONVENTIONS = path.join(CLAUDE_DIR, 'conventions');
const STATE = path.join(CLAUDE_DIR, '.state');
const DECISIONS = path.join(CLAUDE_DIR, 'decisions');

const commands = { init, scan, stale, status, contract, evidence, 'codecraft-done': codecraftDone, 'hook-stop': hookStop, help };
(commands[command] ?? help)();

function help() {
  console.log(`kit — project side of the .NET AI kit

  kit init               create .claude/ skeleton, .gitattributes, .gitignore, CLAUDE.md import
  kit scan [topic…]      regenerate conventions (all topics, or only the named ones)
  kit scan --check       exit 1 if a committed convention no longer matches the code
  kit stale              same as --check, with a reason per file
  kit status             what is set up, what is stale, which tools are reachable
  kit contract [name]    list contracts, or print one
  kit evidence [topic]   raw counts and file lists behind the conventions (for convention-creator)
  kit codecraft-done     record that the current diff has been checked
  topics: ${SCANNERS.map((s) => s.topic).join(', ')}`);
}

function renderTopic(scanner, result) {
  const esc = (v) => String(v).replace(/\|/g, '\\|');
  const width = Math.max(4, ...result.facts.map(([k]) => k.length));
  const lines = [
    `# ${scanner.topic[0].toUpperCase()}${scanner.topic.slice(1)}`,
    '',
    `<!-- generated by \`kit scan\` · inputs: ${scanner.inputs.join(', ')} · do not edit: decisions go in .claude/decisions/ -->`,
    '',
    `| ${'fact'.padEnd(width)} | value |`,
    `| ${'-'.repeat(width)} | ----- |`,
    ...result.facts.map(([k, v]) => `| ${esc(k).padEnd(width)} | ${esc(v)} |`),
    '',
  ];
  if (result.notes.length) {
    lines.push('## Notes', '', ...result.notes.map((n) => `- ${n}`), '');
  }
  return lines.join('\n');
}

/** Everything `kit scan` would write, as { relative path under .claude/: content }. */
function generate(only) {
  const ctx = loadContext(root);
  if (!ctx) {
    console.error('No .sln, .slnx or project file found at the git root or up to three levels below it.');
    process.exit(2);
  }
  const committed = {};
  const evidence = {};
  const scanners = only.length ? SCANNERS.filter((s) => only.includes(s.topic)) : SCANNERS;
  for (const scanner of scanners) {
    const result = scanner.run(ctx);
    committed[`conventions/${scanner.topic}.md`] = renderTopic(scanner, result);
    evidence[scanner.topic] = result.evidence;
  }
  if (!only.length || only.includes('packages')) {
    for (const pkg of scanPackages(ctx)) {
      committed[`conventions/${pkg.file}`] = pkg.content;
    }
  }
  const topics = SCANNERS.map((s) => s.topic).filter((t) => only.length === 0 || only.includes(t) || fs.existsSync(path.join(CONVENTIONS, `${t}.md`)));
  committed['conventions/_router.md'] = buildRouter(ctx, topics, fs.existsSync(DECISIONS));
  const local = {
    '.state/inventory.md': buildInventory(ctx),
    '.state/evidence.json': JSON.stringify(evidence, null, 2) + '\n',
  };
  return { committed, local };
}

function scan() {
  const only = positional;
  const unknown = only.filter((t) => t !== 'packages' && !SCANNERS.some((s) => s.topic === t));
  if (unknown.length) {
    console.error(`Unknown topic(s): ${unknown.join(', ')}`);
    process.exit(2);
  }
  const { committed, local } = generate(only);
  if (flags.has('--check')) {
    const stale = diffAgainstDisk(committed, only.length === 0);
    if (stale.length) {
      console.log('stale:\n' + stale.map((s) => `  ${s}`).join('\n'));
      process.exit(1);
    }
    console.log('conventions are up to date');
    return;
  }
  let changed = 0;
  for (const [rel, content] of Object.entries({ ...committed, ...local })) {
    if (writeIfChanged(path.join(CLAUDE_DIR, rel), content)) {
      changed++;
      console.log(`wrote .claude/${rel}`);
    }
  }
  if (only.length === 0) {
    for (const rel of orphanedPackageFiles(committed)) {
      fs.rmSync(path.join(CLAUDE_DIR, rel));
      console.log(`removed .claude/${rel}`);
      changed++;
    }
  }
  console.log(changed ? `${changed} file(s) updated` : 'nothing changed');
}

function orphanedPackageFiles(committed) {
  const dir = path.join(CONVENTIONS, 'packages');
  if (!fs.existsSync(dir)) return [];
  return fs.readdirSync(dir)
    .map((f) => `conventions/packages/${f}`)
    .filter((rel) => !(rel in committed));
}

function diffAgainstDisk(committed, includeOrphans) {
  const stale = [];
  for (const [rel, content] of Object.entries(committed)) {
    const current = readText(path.join(CLAUDE_DIR, rel));
    if (current === null) stale.push(`.claude/${rel} (missing)`);
    else if (current.replace(/\r\n/g, '\n') !== content) stale.push(`.claude/${rel} (differs from the code)`);
  }
  if (includeOrphans) {
    stale.push(...orphanedPackageFiles(committed).map((rel) => `.claude/${rel} (package no longer configured)`));
  }
  return stale;
}

function stale() {
  const { committed } = generate([]);
  const ctx = loadContext(root);
  const lines = [];
  for (const rel of Object.keys(committed).filter((r) => r.startsWith('conventions/packages/'))) {
    const current = readText(path.join(CLAUDE_DIR, rel)) ?? '';
    const scanned = /^scanned:\s*(\S+)/m.exec(current)?.[1];
    const resolved = /^resolved:\s*(\S+)/m.exec(committed[rel])?.[1];
    if (scanned && resolved && scanned !== resolved) {
      const major = scanned.split('.')[0] !== resolved.split('.')[0];
      lines.push(`stale  ${rel.padEnd(44)} ${scanned} ≠ ${resolved}  ${major ? 'major → full scan, review the API section' : 'patch/minor → rescan'}`);
    }
  }
  const differing = diffAgainstDisk(committed, true);
  for (const entry of differing) {
    if (!lines.some((l) => entry.includes(l.split(/\s+/)[1]))) lines.push(`stale  ${entry}`);
  }
  if (!ctx) return;
  if (lines.length === 0) {
    console.log('ok     all conventions match the code');
    return;
  }
  console.log(lines.join('\n'));
  console.log('\nRun `kit scan` to regenerate, then review the diff.');
  process.exit(1);
}

function status() {
  const hasConventions = fs.existsSync(path.join(CONVENTIONS, '_router.md'));
  const ctx = loadContext(root);
  const row = (label, value) => console.log(`${label.padEnd(30)} ${value}`);
  row('project root', root);
  row('solution', ctx ? `${ctx.ws === '.' ? '' : ctx.ws + '/'}${ctx.solution ?? '(no solution file, projects only)'}` : 'NOT FOUND');
  row('conventions', hasConventions ? 'present' : 'missing → run `kit init` then `kit scan`');
  if (hasConventions && ctx) {
    const differing = diffAgainstDisk(generate([]).committed, true);
    row('freshness', differing.length ? `${differing.length} stale → \`kit stale\`` : 'up to date');
  }
  row('decisions/', fs.existsSync(DECISIONS) ? 'present' : 'missing');
  row('CLAUDE.md imports router', claudeMdImportsRouter() ? 'yes' : 'no → run `kit init`');

  const sdks = run('dotnet', ['--list-sdks'], ctx?.wsAbs ?? root);
  const installed = (sdks ?? '').split('\n').map((l) => l.split(' ')[0]).filter(Boolean);
  row('.NET SDKs', installed.length ? installed.join(', ') : 'dotnet not on PATH → https://dot.net/download');
  const pin = ctx?.globalJson?.sdk?.version;
  if (pin) {
    const major = pin.split('.')[0];
    row('global.json SDK pin', `${pin}${installed.some((v) => v.split('.')[0] === major) ? '' : ' → no SDK of that major installed'}`);
  }
  const newest = Math.max(0, ...installed.map((v) => Number(v.split('.')[0])));
  row('dotnet dnx (Roslyn LSP, NuGet MCP)', newest >= 10 ? 'available (.NET 10+ SDK)' : 'missing → install the .NET 10 SDK or newer; the LSP and the NuGet MCP need it');
  const efTool = onPath('dotnet-ef') || fs.existsSync(path.join(os.homedir(), '.dotnet', 'tools', process.platform === 'win32' ? 'dotnet-ef.exe' : 'dotnet-ef'));
  const facts = ctx ? routerFacts(ctx) : null;
  if (facts?.efCore) {
    const efVersion = ctx.resolved('Microsoft.EntityFrameworkCore') ?? '?';
    row('dotnet-ef', efTool ? `installed (project uses EF Core ${efVersion}; keep the same major)` : `missing → dotnet tool install --global dotnet-ef --version ${efVersion.split('.')[0]}.*`);
  }
  if (facts?.windowsOnly.length) {
    row('Windows-only projects', `${facts.windowsOnly.join(', ')}${process.platform === 'win32' ? '' : ' → cannot be built on this machine'}`);
  }
  row('node (kit CLI, Stop hook)', process.version);
  const plugins = installedPlugins();
  for (const name of OFFICIAL_PLUGINS) {
    row(`${name}@${OFFICIAL_MARKETPLACE}`, plugins === null ? 'unknown (no ~/.claude/plugins/installed_plugins.json)' : plugins[name] ?? 'NOT INSTALLED → /plugin marketplace add dotnet/skills, then reinstall kit-dotnet');
  }
  const config = readJsonc(path.join(CLAUDE_DIR, 'kit.json'));
  row('codecraft enforcement', config?.enforceCodecraft === false ? 'off (kit.json)' : 'on (Stop hook)');
}

function run(file, runArgs, cwd) {
  try {
    return execFileSync(file, runArgs, { cwd, encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'], timeout: 15000 });
  } catch {
    return null;
  }
}

/**
 * Versions of the official plugins as Claude Code recorded them, or null when the file isn't
 * there. The file's layout isn't a public contract, so this only looks for "<name>@<marketplace>"
 * keys and a version string below them.
 */
function installedPlugins() {
  const data = readJsonc(path.join(os.homedir(), '.claude', 'plugins', 'installed_plugins.json'));
  if (!data) return null;
  const found = {};
  const versionIn = (value) => {
    if (!value || typeof value !== 'object') return null;
    if (typeof value.version === 'string') return value.version;
    for (const v of Object.values(value)) {
      const hit = versionIn(v);
      if (hit) return hit;
    }
    return null;
  };
  const visit = (node) => {
    if (!node || typeof node !== 'object') return;
    for (const [key, value] of Object.entries(node)) {
      const m = new RegExp(`^([\\w-]+)@${OFFICIAL_MARKETPLACE}$`).exec(key);
      if (m) found[m[1]] = versionIn(value) ?? 'installed';
      else visit(value);
    }
  };
  visit(data);
  return found;
}

function claudeMdImportsRouter() {
  return ['CLAUDE.md', '.claude/CLAUDE.md'].some((f) => /_router\.md/.test(readText(path.join(root, f)) ?? ''));
}

function contract() {
  const contracts = listContracts();
  const name = positional[0];
  if (!name) {
    for (const c of contracts) console.log(`${c.name.padEnd(30)} ${c.status ?? ''}  ${c['applies-when'] ?? ''}`);
    return;
  }
  const found = contracts.find((c) => c.name === name);
  if (!found) {
    console.error(`No contract "${name}". Known: ${contracts.map((c) => c.name).join(', ')}`);
    process.exit(1);
  }
  process.stdout.write(found.text);
}

function evidence() {
  const data = readJsonc(path.join(STATE, 'evidence.json'));
  if (!data) {
    console.error('No evidence yet: run `kit scan` first.');
    process.exit(1);
  }
  const topic = positional[0];
  console.log(JSON.stringify(topic ? data[topic] ?? {} : data, null, 2));
}

function init() {
  const created = [];
  const ensure = (rel, content) => {
    const file = path.join(root, rel);
    if (!fs.existsSync(file)) {
      fs.mkdirSync(path.dirname(file), { recursive: true });
      fs.writeFileSync(file, content);
      created.push(rel);
    }
  };
  ensure('.claude/kit.json', JSON.stringify({ packages: [], enforceCodecraft: true }, null, 2) + '\n');
  ensure('.claude/decisions/traps.md', '# Traps\n\nThings that look like bugs or invite a cleanup but are deliberate. One entry each: what, and why.\n\n');
  ensure('.claude/decisions/conventions.md', '# Confirmed conventions\n\nRules a human confirmed after a scan (written by the convention-creator skill). Each rule lists its known exceptions.\n\n');
  ensure('.claude/decisions/adr/.gitkeep', '');
  appendLines('.gitattributes', [
    '# kit: generated conventions are rebuilt with `kit scan`, never merged line by line',
    '.claude/conventions/** merge=binary linguist-generated=true',
  ], created);
  appendLines('.gitignore', ['# kit: local scan cache', '.claude/.state/', '.claude/settings.local.json'], created);

  if (!claudeMdImportsRouter()) {
    const target = fs.existsSync(path.join(root, 'CLAUDE.md')) && !fs.existsSync(path.join(root, '.claude', 'CLAUDE.md'))
      ? 'CLAUDE.md'
      : '.claude/CLAUDE.md';
    const importPath = target === 'CLAUDE.md' ? '@.claude/conventions/_router.md' : '@conventions/_router.md';
    const file = path.join(root, target);
    const current = readText(file) ?? '# Project\n';
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, current.replace(/\s*$/, '\n') + `\n## Kit\n\nGenerated map of conventions, decisions and contracts:\n\n${importPath}\n`);
    created.push(`${target} (router import)`);
  }
  console.log(created.length ? created.map((c) => `created/updated ${c}`).join('\n') : 'already initialised');
}

function appendLines(rel, lines, created) {
  const file = path.join(root, rel);
  const current = readText(file) ?? '';
  const missing = lines.filter((l) => l.startsWith('#') ? false : !current.split(/\r?\n/).includes(l));
  if (missing.length) {
    fs.writeFileSync(file, current.replace(/\s*$/, current ? '\n\n' : '') + lines.join('\n') + '\n');
    created.push(rel);
  }
}

/** Hash of the uncommitted code changes (tracked diff + untracked files). Empty string when clean. */
function diffHash() {
  const patterns = ['*.cs', '*.razor', '*.cshtml', '*.xaml', '*.csproj', '*.props', '*.targets', '*.sql'];
  const hasHead = git(['rev-parse', '--verify', 'HEAD'], root) !== null;
  const diff = git(hasHead ? ['diff', 'HEAD', '--', ...patterns] : ['diff', '--', ...patterns], root) ?? '';
  const untracked = (git(['ls-files', '--others', '--exclude-standard', '--', ...patterns], root) ?? '')
    .split('\n').filter(Boolean).sort();
  const untrackedContent = untracked.map((f) => `${f}\n${readText(path.join(root, f)) ?? ''}`).join('\n');
  if (!diff && !untrackedContent) return '';
  return sha256(diff + '\n' + untrackedContent);
}

function codecraftDone() {
  fs.mkdirSync(STATE, { recursive: true });
  fs.writeFileSync(path.join(STATE, 'codecraft.json'), JSON.stringify({ diff: diffHash() }) + '\n');
  console.log('recorded: the current diff has been checked');
}

function hookStop() {
  let input = '';
  try {
    input = fs.readFileSync(0, 'utf8');
  } catch {
    // no stdin: treat as a normal stop
  }
  let payload = {};
  try {
    payload = JSON.parse(input || '{}');
  } catch {
    payload = {};
  }
  // A second stop in the same turn means Claude already reacted to the first block.
  if (payload.stop_hook_active) return;
  if (!fs.existsSync(path.join(CONVENTIONS, '_router.md'))) return;
  if (readJsonc(path.join(CLAUDE_DIR, 'kit.json'))?.enforceCodecraft === false) return;
  const current = diffHash();
  if (!current) return;
  const recorded = readJsonc(path.join(STATE, 'codecraft.json'))?.diff;
  if (recorded === current) return;
  process.stdout.write(JSON.stringify({
    decision: 'block',
    reason: 'Code changed since the last codecraft check. Run the `codecraft` skill on the diff (it ends with `kit codecraft-done`). If this turn made no code change worth checking, say why in one line and run `kit codecraft-done`.',
  }));
}
